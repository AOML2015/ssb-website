(function () {
  const STORAGE_KEY = 'ssb-lang';

  function applyLanguage(lang) {
    const dict = SSB_TRANSLATIONS[lang] || SSB_TRANSLATIONS.en;
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    document.body.classList.toggle('lang-ar', lang === 'ar');

    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key] !== undefined) {
        el.textContent = dict[key];
      }
    });

    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const key = el.getAttribute('data-i18n-html');
      if (dict[key] !== undefined) {
        el.innerHTML = dict[key];
      }
    });

    const toggleText = document.querySelector('.lang-toggle-text');
    if (toggleText) {
      toggleText.textContent = lang === 'ar' ? 'English' : 'العربية';
    }

    localStorage.setItem(STORAGE_KEY, lang);
  }

  function initLanguage() {
    const saved = localStorage.getItem(STORAGE_KEY) || 'en';
    applyLanguage(saved);

    const toggleBtn = document.getElementById('lang-toggle');
    if (toggleBtn) {
      toggleBtn.addEventListener('click', () => {
        const current = document.documentElement.lang === 'ar' ? 'ar' : 'en';
        const next = current === 'ar' ? 'en' : 'ar';
        applyLanguage(next);
      });
    }
  }

  document.addEventListener('DOMContentLoaded', initLanguage);
})();
